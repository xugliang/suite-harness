"""Version-one PostgreSQL DDL, explicitly reviewed rather than guessed from SQLite.

Timestamps and canonical JSON retain the existing TEXT representation for
lossless migration. Epoch microseconds and counters use BIGINT. Only the audit
sequence is generated by PostgreSQL; transcript sequences are per session.
"""

import re

_BEIJING_ISO_BODY = """(value TEXT) RETURNS TEXT LANGUAGE plpgsql IMMUTABLE STRICT
SET search_path = pg_catalog AS $function$
DECLARE normalized TEXT; instant TIMESTAMPTZ;
BEGIN
  IF value ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN
    normalized := value || 'T00:00:00+00:00';
  ELSIF value ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}[T ][0-9]{2}:[0-9]{2}:[0-9]{2}([.][0-9]+)?(Z|[+-][0-9]{2}:[0-9]{2})?$' THEN
    normalized := CASE WHEN value ~ '(Z|[+-][0-9]{2}:[0-9]{2})$' THEN value ELSE value || '+00:00' END;
  ELSE RETURN NULL;
  END IF;
  instant := normalized::TIMESTAMPTZ;
  RETURN to_char((instant AT TIME ZONE 'UTC') + INTERVAL '8 hours 0.0005 seconds', 'YYYY-MM-DD HH24:MI:SS') || '+08:00';
EXCEPTION WHEN invalid_datetime_format OR datetime_field_overflow THEN RETURN NULL;
END;
$function$"""

_BEIJING_EPOCH_BODY = """(value DOUBLE PRECISION) RETURNS TEXT LANGUAGE plpgsql IMMUTABLE STRICT
SET search_path = pg_catalog AS $function$
BEGIN
  IF value IN ('Infinity'::DOUBLE PRECISION, '-Infinity'::DOUBLE PRECISION, 'NaN'::DOUBLE PRECISION) THEN RETURN NULL; END IF;
  RETURN to_char(TIMESTAMP '1970-01-01 00:00:00' + value * INTERVAL '1 second' + INTERVAL '8 hours 0.0005 seconds', 'YYYY-MM-DD HH24:MI:SS') || '+08:00';
EXCEPTION WHEN datetime_field_overflow OR numeric_value_out_of_range THEN RETURN NULL;
END;
$function$"""


def beijing_function_ddl(schema: str | None = None) -> tuple[str, ...]:
    """Explicit reusable DDL for SQLite-compatible UTC+8 display functions.

    ISO inputs are constrained to unambiguous numeric ISO dates before parsing;
    timezone-free values explicitly mean UTC. The fixed numeric format and UTC
    conversion make these wrappers independent of session timezone and locale.
    The half-millisecond adjustment matches SQLite datetime() second display.
    """
    if schema is not None and not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", schema):
        raise ValueError("invalid Beijing function schema")
    prefix = "" if schema is None else '"' + schema + '".'
    return (
        "CREATE OR REPLACE FUNCTION " + prefix + "suiteharness_beijing_iso" + _BEIJING_ISO_BODY,
        "CREATE OR REPLACE FUNCTION " + prefix + "suiteharness_beijing_epoch" + _BEIJING_EPOCH_BODY,
    )


