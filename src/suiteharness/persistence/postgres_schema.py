def _beijing_schema():
    statements = list(beijing_function_ddl())
    for table, columns in BEIJING_DERIVED_COLUMNS.items():
        for target, source, kind in columns:
            expression = ("suiteharness_beijing_iso(" + source + ")" if kind == "iso" else
                          "suiteharness_beijing_epoch(" + source + (" / 1000000.0" if kind == "micros" else "") + ")")
            statements.append(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {target} TEXT GENERATED ALWAYS AS ({expression}) STORED")
    return tuple(statements)

